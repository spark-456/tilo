export const makeWorld = (mode: TierKey, q: string, i: number): World => {
  const T = TIERS[mode];
  const name = q || T.ph;
  return {
    id: `new${i}`,
    name,
    short: name.length > 26 ? `${name.slice(0, 24)}…` : name,
    tier: T.tier,
    tool: T.tool,
    st: "running",
    isNew: true,
    meta: "Started just now",
    agents: T.agents,
    prog: 4,
    spend: "£0.00",
    of: T.tier === "City" ? "of £400" : "",
    spendV: 0,
    budget: T.tier === "City" ? 400 : 0,
    nextL: "Status",
    nextV: "Starting",
    when: "Starting now",
    owner: "Alex Morgan",
    started: "Just now",
    plan: T.tier === "City" ? "fresh" : null,
    single: T.tier === "Village" ? ["desk", "active", "research"] : null,
    row:
      T.tier === "Town"
        ? [
            ["clock", "active", "hall"],
            ["desk", "idle", "mail"],
          ]
        : null,
    districts:
      T.tier === "City"
        ? [
            {
              name: "Town Hall",
              icon: "hall",
              done: 0,
              total: 1,
              agents: 1,
              st: "running",
              note: "Director is drafting the plan",
            },
          ]
        : null,
    runs: T.tier === "Town" ? [] : null,
    out: T.tier === "Village" ? "Working on it. You’ll get a notification when it’s ready." : null,
    activity: [
      {
        t: "Just now",
        rank: "director",
        who: "Director",
        text: "Read your brief and started planning.",
        kind: "info",
      },
    ],
  };
};
