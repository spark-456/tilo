import AxeBuilder from "@axe-core/playwright";
import { type Page, expect, test } from "@playwright/test";
import { watchConsole } from "./support/screens";
import { readShifts, resetShifts, watchShifts } from "./support/shifts";
import { DESKTOP, MOBILE } from "./support/viewports";
import { canvasSnapshot, fixtureUrl, stageFrame, stageSeq, traceRows } from "./support/world";

// FR-WLD-07 (web): "Pause all stops every agent in <= 2 s and shows a veil". The veil, the HUD
// word "Paused" and the frozen stage all come from a recorded world.paused (HR-1); events that
// still arrive after it are recorded (Trace) but never animated (HR-1, HR-3). pause-6 is a 6-agent
// run, generated by `make-crowd-fixture.mjs 6 --pause-after=3`: world.paused is seq 24 and 15
// straggler agent.moved events follow it (a real server sends none; the web app must still hold).

const PAUSED_SEQ = 24;
const LAST_SEQ = 39;
const veil = (page: Page) => page.getByTestId("world-veil");
const slot = (page: Page) => page.getByTestId("pause-slot");

async function waitForSeq(page: Page, seq: number, timeout = 20_000) {
  await expect.poll(() => stageSeq(page), { timeout, intervals: [25] }).toBeGreaterThanOrEqual(seq);
}

test.describe("FR_WLD_07 recorded pause on the stage (6-agent run)", () => {
  test.use({ viewport: DESKTOP });

  test("FR_WLD_07 no veil before world.paused; veil, Paused HUD and a frozen stage after it", async ({
    page,
  }) => {
    test.setTimeout(60_000);
    const problems = watchConsole(page);
    await watchShifts(page);
    await page.goto(fixtureUrl("pause-6"));
    await expect(stageFrame(page)).toHaveAttribute("data-stage-ready", "true");
    await waitForSeq(page, 9);
    await expect(veil(page)).toHaveCount(0); // HR-1: nothing claims a pause before the event
    await expect(stageFrame(page)).not.toHaveAttribute("data-paused", "true");
    await expect(slot(page)).toHaveAttribute("data-pause", "unavailable");
    await resetShifts(page);

    await waitForSeq(page, PAUSED_SEQ);
    await expect(veil(page)).toBeVisible();
    await expect(veil(page)).toContainText("Paused");
    await expect(stageFrame(page)).toHaveAttribute("data-paused", "true");
    await expect(slot(page)).toHaveAttribute("data-pause", "paused");
    await expect(slot(page)).toContainText("All work is paused");
    await expect(page.getByTestId("resume")).toHaveAttribute("aria-disabled", "true");

    // No motion: the veil is static (HR-2) and the canvas holds still while stragglers arrive.
    const style = await veil(page).evaluate((el) => {
      const s = getComputedStyle(el);
      return { animation: s.animationName, transition: s.transitionDuration };
    });
    expect(style.animation).toBe("none");
    expect(style.transition).toBe("0s");
    const frozen = await canvasSnapshot(page);
    await waitForSeq(page, LAST_SEQ);
    expect(await canvasSnapshot(page)).toBe(frozen);
    // The stragglers are recorded, not hidden (HR-5 style honesty: the Trace lists every event).
    await expect(traceRows(page)).toHaveCount(LAST_SEQ);
    await expect(traceRows(page).filter({ hasText: "world.paused" })).toHaveCount(1);
    expect(await readShifts(page)).toEqual([]);
    expect(problems).toEqual([]);
  });

  test("FR_WLD_07 events after the pause really are not drawn: the unpaused state differs", async ({
    page,
  }) => {
    test.setTimeout(60_000);
    await page.goto(fixtureUrl("pause-6"));
    await waitForSeq(page, LAST_SEQ);
    const held = await canvasSnapshot(page);
    await page.goto(fixtureUrl("pause-6", { seq: LAST_SEQ }));
    await expect(stageFrame(page)).toHaveAttribute("data-seq", String(LAST_SEQ));
    // The static frame at the last seq has every straggler's move applied; the held one does not.
    expect(await canvasSnapshot(page)).not.toBe(held);
  });

  test("FR_WLD_07 a static frame at the paused seq shows the veil too", async ({ page }) => {
    await page.goto(fixtureUrl("pause-6", { seq: PAUSED_SEQ }));
    await expect(stageFrame(page)).toHaveAttribute("data-seq", String(PAUSED_SEQ));
    await expect(veil(page)).toBeVisible();
    await page.goto(fixtureUrl("pause-6", { seq: PAUSED_SEQ - 1 }));
    await expect(stageFrame(page)).toHaveAttribute("data-seq", String(PAUSED_SEQ - 1));
    await expect(veil(page)).toHaveCount(0);
  });

  test("FR_WLD_07 a recorded replay cannot be paused: the control says so", async ({ page }) => {
    await page.goto(fixtureUrl("pause-6", { seq: 5 }));
    const button = page.getByTestId("pause-all");
    await expect(button).toBeVisible();
    await expect(button).toHaveAttribute("aria-disabled", "true");
    await expect(button).toHaveAttribute("title", /recorded replay/);
  });
});

test.describe("FR_WLD_07 Pause all from the world screens (fixture client)", () => {
  test("FR_WLD_07 click shows Pausing... until the event is recorded, then the veil and Paused", async ({
    page,
  }) => {
    test.setTimeout(60_000);
    const problems = watchConsole(page);
    await watchShifts(page);
    await page.setViewportSize(DESKTOP);
    // The 900 ms request latency keeps "Pausing…" on screen long enough to look at.
    await page.goto("/world/w_village_basic?speed=10&client_delay_ms=900");
    const hud = page.getByTestId("hud-meter");
    await expect(hud).toContainText("Working", { timeout: 20_000 });
    await expect(veil(page)).toHaveCount(0);
    await resetShifts(page);

    const button = page.getByTestId("pause-all");
    await button.focus();
    await page.keyboard.press("Enter"); // keyboard accessible
    await expect(slot(page)).toHaveAttribute("data-pause", "pausing");
    await expect(slot(page)).toContainText("Pausing…");
    await expect(veil(page)).toHaveCount(0); // a click is a request, not a claim (HR-1)
    await expect(hud).not.toContainText("Paused");

    await expect(slot(page)).toHaveAttribute("data-pause", "paused");
    await expect(veil(page)).toBeVisible();
    await expect(hud).toContainText("Paused");
    await expect(stageFrame(page)).toHaveAttribute("data-paused", "true");

    // Nothing more is recorded: the figures stay put for longer than the 2 s limit.
    const figures = await hud.innerText();
    await page.waitForTimeout(2500);
    expect(await hud.innerText()).toBe(figures);
    await expect(page.locator("button.primary")).toHaveCount(0); // UX-1: Pause all is not filled
    const axe = await new AxeBuilder({ page })
      .withTags(["wcag2a", "wcag2aa", "wcag22aa"])
      .analyze();
    expect(axe.violations).toEqual([]);
    expect(await readShifts(page)).toEqual([]);
    expect(problems).toEqual([]);
  });

  test("FR_WLD_07 the Story lens shows the recorded pause and the control stays reachable", async ({
    page,
  }) => {
    test.setTimeout(60_000);
    await page.setViewportSize(DESKTOP);
    await page.goto("/world/w_village_basic/story?speed=10");
    await expect(page.getByTestId("story-lens")).toContainText("Replaying", { timeout: 20_000 });
    await page.getByTestId("pause-all").click();
    await expect(slot(page)).toHaveAttribute("data-pause", "paused");
    await expect(page.getByTestId("story-lens")).toContainText("You paused all work.");
  });

  test("FR_WLD_07 on mobile the control is 44 px and one tap inside World status", async ({
    page,
  }) => {
    test.setTimeout(60_000);
    await page.setViewportSize(MOBILE);
    await page.goto("/world/w_village_basic?speed=10");
    await page.getByText("World status").click();
    const button = page.getByTestId("pause-all");
    const box = await button.boundingBox();
    expect(box?.height ?? 0).toBeGreaterThanOrEqual(44);
    expect(box?.width ?? 0).toBeGreaterThanOrEqual(44);
    await button.click();
    await expect(veil(page)).toBeVisible({ timeout: 10_000 });
    await expect(slot(page)).toHaveAttribute("data-pause", "paused");
  });
});
