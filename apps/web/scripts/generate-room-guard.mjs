// MR-01: compile the existing schema at development time; hosting CSP forbids runtime compilation.
import { readFileSync, writeFileSync } from "node:fs";
import Ajv2020 from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";

const load = (name) =>
  JSON.parse(
    readFileSync(new URL(`../../../contracts/${name}.schema.json`, import.meta.url), "utf8"),
  );
const ajv = new Ajv2020({
  strict: false,
  validateFormats: false,
  code: { source: true, esm: true },
});
const validate = ajv.addSchema(load("common")).compile(load("meeting_room"));
const code = standalone(ajv, validate)
  .replaceAll('require("ajv/dist/runtime/ucs2length").default', "ucs2length")
  .replaceAll('require("ajv/dist/runtime/equal").default', "equal");
if (/\brequire\(/.test(code)) throw new Error(JSON.stringify(code.match(/require\([^)]*\)/g)));
const header =
  '// Generated by apps/web/scripts/generate-room-guard.mjs; do not hand edit.\nimport equalModule from "ajv/dist/runtime/equal.js";\nimport lengthModule from "ajv/dist/runtime/ucs2length.js";\nconst ucs2length = lengthModule.default ?? lengthModule;\nconst equal = equalModule.default ?? equalModule;\n';
const name = /export default (\w+);/.exec(code)?.[1];
if (!name) throw new Error("Validator default export was not found.");
const body = code.replace(/export (?:const validate = \w+|default \w+);/g, "");
const file = new URL("../src/park/api/live/meetingRoom.guard.js", import.meta.url);
const output = `${header}const validateRoom = (() => {${body}return ${name};})();\nexport default validateRoom;\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(file, "utf8") !== output) throw new Error("Regenerate the room validator.");
} else writeFileSync(file, output);
