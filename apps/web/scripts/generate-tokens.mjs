// Writes src/styles/tokens.css and src/design/tokens.ts from design/tokens.json (`just tokens`).
// BQ-10: PRD 18.2 values win over the exports. BQ-11: null colour roles get a neutral grey.
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const at = (p) => fileURLToPath(new URL(p, import.meta.url));
export const CSS_PATH = at("../src/styles/tokens.css");
export const TS_PATH = at("../src/design/tokens.ts");
const GREY = "#8a8a8a";
const MISSING = " /* missing in design exports */";
const HEADER = "AUTO-GENERATED by apps/web/scripts/generate-tokens.mjs; run `just tokens`.";
// JSON.parse reviver: `{ value, ... }` leaves become their value (null: GREY); notes are dropped.
const leaf = (k, v) => {
  if (k === "unmapped" || (typeof v === "string" && k !== "value")) return undefined;
  return v?.constructor === Object && "value" in v ? (v.value ?? GREY) : v;
};
const flat = (o, p = []) =>
  Object.entries(o).flatMap(([k, v]) => (typeof v === "object" ? flat(v, [...p, k]) : [[p, k, v]]));

export function generate() {
  const raw = JSON.parse(fs.readFileSync(at("../../../design/tokens.json"), "utf-8"), leaf);
  const t = {
    color: raw.color,
    radius: { controls: 12, cards: 20, pill: 999 }, // PRD "Shape" (exports: 16/24)
    button: { height: { desktop: 48, mobile: 52 } }, // PRD "Pressable button" (exports: 56 mobile)
    motion: { pressMs: 120, sheetsMs: 200, cameraMs: 320 }, // PRD "Motion" (exports: 100/-/650)
    font: { ...raw.font.family, stageModeScale: 1.25 }, // PRD "Type": stage mode x 1.25
    stage: { tileWidth: 64, tileHeight: 32 }, // no PRD/export value: standard 2:1 iso diamond
  };
  const { color, radius, button, motion, font } = t;
  const vars = flat({ color, radius, button, motion }).map(([p, k, v]) => {
    const name = [...p, k.replace(/Ms$/, "-ms")].join("-");
    if (typeof v === "string") return `--${name}: ${v.toLowerCase()};${v === GREY ? MISSING : ""}`;
    return `--${name}: ${v}${name.endsWith("-ms") ? "ms" : "px"};`;
  });
  vars.push(
    `--font-display: "${font.display}", sans-serif;`,
    `--font-ui: "${font.ui}", sans-serif;`,
  );
  vars.push(
    `--font-mono: "${font.mono}", monospace;`,
    `--font-stage-mode-scale: ${font.stageModeScale};`,
  );
  return {
    css: `/* ${HEADER} */\n:root {\n  ${vars.join("\n  ")}\n}\n`,
    ts: `// ${HEADER}\nexport const tokens = ${JSON.stringify(t, null, 2)} as const;\nexport default tokens;\n`,
  };
}

if (process.argv[1]?.endsWith("generate-tokens.mjs")) {
  const { css, ts } = generate();
  fs.writeFileSync(CSS_PATH, css);
  fs.writeFileSync(TS_PATH, ts);
}
