#!/usr/bin/env node
// Generates apps/web/src/styles/tokens.css and apps/web/src/design/tokens.ts
// from design/tokens.json (PRD 18.2). Regenerate with `just tokens`; the
// tokens.drift.test.ts test fails if the committed files go stale.
//
// BQ-10: PRD 18.2 wins wherever the design exports disagree (radius, button
// height, motion durations) — never the exported value. BQ-11: colour roles
// with no exported value (signal.gate, policy, ink.3) get a neutral grey
// fallback marked "missing in design exports"; never an invented brand colour.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
export const REPO_ROOT = path.resolve(path.dirname(__filename), "..", "..", "..");
const TOKENS_JSON_PATH = path.join(REPO_ROOT, "design", "tokens.json");
export const CSS_PATH = path.join(REPO_ROOT, "apps", "web", "src", "styles", "tokens.css");
export const TS_PATH = path.join(REPO_ROOT, "apps", "web", "src", "design", "tokens.ts");
const FALLBACK_GREY = "#8a8a8a";

const isLeaf = (n) =>
  typeof n === "object" && n !== null && !Array.isArray(n) && Object.hasOwn(n, "value");

/** Walks design/tokens.json's `color` tree into [{path, value}] (value null = missing). */
export function readColorRoles(raw) {
  const roles = [];
  const walk = (node, segs) => {
    if (segs[0] === "unmapped" || typeof node !== "object" || node === null || Array.isArray(node))
      return;
    if (isLeaf(node)) {
      roles.push({ path: segs.join("."), value: node.value === null ? null : String(node.value) });
      return;
    }
    for (const [key, child] of Object.entries(node)) walk(child, [...segs, key]);
  };
  walk(raw.color ?? {}, []);
  return roles;
}

function setPath(obj, segs, value) {
  let cur = obj;
  for (let i = 0; i < segs.length - 1; i++) cur = cur[segs[i]] ??= {};
  cur[segs.at(-1)] = value;
}

/** Nested `tokens` object: colour roles (fallback applied) plus the PRD 18.2
 * radius/button/motion/type values, overriding the design exports (BQ-10). */
export function buildTokens(raw, colorRoles) {
  const color = {};
  for (const role of colorRoles) setPath(color, role.path.split("."), role.value ?? FALLBACK_GREY);
  return {
    color,
    // controls/cards: PRD 18.2 "Shape" (exports say 16/24px — BQ-10). pill: no disagreement.
    radius: { controls: 12, cards: 20, pill: 999 },
    // PRD 18.2 "Pressable button" (exports say 56px mobile in prose — BQ-10).
    button: { height: { desktop: 48, mobile: 52 } },
    // PRD 18.2 "Motion" (exports: press 100ms, no sheets value, camera 650ms — BQ-10).
    motion: { pressMs: 120, sheetsMs: 200, cameraMs: 320 },
    font: {
      display: raw.font?.family?.display?.value ?? "Nunito",
      ui: raw.font?.family?.ui?.value ?? "Nunito Sans",
      mono: raw.font?.family?.mono?.value ?? "JetBrains Mono",
      scalePx: [12, 14, 16, 20, 24, 32, 40], // PRD 18.2 "Type"
      stageModeScale: 1.25, // PRD 18.2 "Type": "stage mode × 1.25"
    },
    // No PRD/export value defines an iso tile size; standard 2:1 diamond ratio.
    stage: { tileWidth: 64, tileHeight: 32 },
  };
}

export function buildCss(tokens, colorRoles) {
  const missing = new Set(colorRoles.filter((r) => r.value === null).map((r) => r.path));
  const lines = [
    "/* AUTO-GENERATED by apps/web/scripts/generate-tokens.mjs from design/tokens.json. */",
    "/* Regenerate with `just tokens`. Do not hand-edit (PRD 18.2, BQ-10, BQ-11). */",
    ":root {",
  ];
  for (const role of colorRoles) {
    const comment = missing.has(role.path) ? " /* missing in design exports */" : "";
    lines.push(
      `  --color-${role.path.split(".").join("-")}: ${role.value ?? FALLBACK_GREY};${comment}`,
    );
  }
  lines.push(
    `  --radius-controls: ${tokens.radius.controls}px;`,
    `  --radius-cards: ${tokens.radius.cards}px;`,
    `  --radius-pill: ${tokens.radius.pill}px;`,
    `  --button-height-desktop: ${tokens.button.height.desktop}px;`,
    `  --button-height-mobile: ${tokens.button.height.mobile}px;`,
    `  --motion-press-ms: ${tokens.motion.pressMs}ms;`,
    `  --motion-sheets-ms: ${tokens.motion.sheetsMs}ms;`,
    `  --motion-camera-ms: ${tokens.motion.cameraMs}ms;`,
    `  --font-display: "${tokens.font.display}", sans-serif;`,
    `  --font-ui: "${tokens.font.ui}", sans-serif;`,
    `  --font-mono: "${tokens.font.mono}", monospace;`,
    `  --font-stage-mode-scale: ${tokens.font.stageModeScale};`,
    "}",
    "",
  );
  return lines.join("\n");
}

export const buildTs = (tokens) =>
  [
    "// AUTO-GENERATED by apps/web/scripts/generate-tokens.mjs from design/tokens.json.",
    "// Regenerate with `just tokens`. Do not hand-edit (PRD 18.2, BQ-10, BQ-11).",
    `export const tokens = ${JSON.stringify(tokens, null, 2)} as const;`,
    "export type Tokens = typeof tokens;",
    "export default tokens;",
    "",
  ].join("\n");

export function generate() {
  const raw = JSON.parse(fs.readFileSync(TOKENS_JSON_PATH, "utf-8"));
  const colorRoles = readColorRoles(raw);
  const tokens = buildTokens(raw, colorRoles);
  return { css: buildCss(tokens, colorRoles), ts: buildTs(tokens) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  const { css, ts } = generate();
  fs.mkdirSync(path.dirname(CSS_PATH), { recursive: true });
  fs.mkdirSync(path.dirname(TS_PATH), { recursive: true });
  fs.writeFileSync(CSS_PATH, css);
  fs.writeFileSync(TS_PATH, ts);
  console.log(
    `wrote ${path.relative(REPO_ROOT, CSS_PATH)} and ${path.relative(REPO_ROOT, TS_PATH)}`,
  );
}
