// Writes the data files of src/park/api/fixtures/ from the Park City prototype (WEB-1a).
// Run: node apps/web/scripts/park-fixtures.mjs && pnpm exec biome format --write apps/web/src/park/api/fixtures
// The prototype (design_handoff_tilo_web_app/design/tilo-app.js, the user's own design) runs in a vm;
// each data member is written as its end state, verbatim. The functions (plans, worlds, makeWorld,
// needsLeft, gbp) are hand-ported in fixtures/worlds.ts and fixtures/index.ts, and the parity test
// (fixtures.parity.test.ts) compares both sides.
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const at = (p) => fileURLToPath(new URL(p, import.meta.url));
const win = {};
vm.runInNewContext(
  fs.readFileSync(at("../../../design_handoff_tilo_web_app/design/tilo-app.js"), "utf8"),
  { window: win },
);
const data = win.TiloApp.data;

// file -> [[export name, type, prototype member]]
const FILES = {
  user: [
    ["user", "User", "user"],
    ["today", "Today", "today"],
  ],
  decisions: [["decisions", "Decision[]", "decisions"]],
  tiers: [
    ["LEVELS", "string[]", "LEVELS"],
    ["TIERS", "Record<TierKey, Tier>", "TIERS"],
  ],
  skills: [["skills", "Skill[]", "skills"]],
  learn: [["learn", "Learn", "learn"]],
  ledger: [["ledger", "Ledger", "ledger"]],
  agenda: [["agenda", "Agenda", "agenda"]],
  team: [["team", "Team", "team"]],
  connectors: [["connectors", "Connector[]", "connectors"]],
  notifications: [["notifications", "Notification[]", "notifications"]],
};

// ADDITIVE members: designed copy the reference shell hard-codes in `Tilo App.dc.html` (decide() toasts and the
// notification titles once a decision is approved) that the prototype's data does not carry. The shell reads
// them through the Api, so no scenario text lives in app code. The parity test lists these paths and pins
// each value to the string found in the reference shell; every other property is still the prototype's.
const ADDITIVE = {
  decisions: {
    depot: {
      toast: "Approved £3,420 for Laptop Depot",
      approvedTitle: "You approved Laptop Depot",
    },
    mail: {
      toast: "Supplier brief sent to 3 suppliers",
      approvedTitle: "You sent the supplier brief",
    },
  },
};
const withAdditive = (member, value) =>
  member === "decisions" ? value.map((d) => ({ ...d, ...ADDITIVE.decisions[d.k] })) : value;

for (const [file, members] of Object.entries(FILES)) {
  const names = [...new Set(members.flatMap(([, type]) => type.match(/[A-Z]\w+/g)))]
    .filter((n) => n !== "Record")
    .sort();
  const body = members
    .map(
      ([name, type, key]) =>
        `export const ${name}: ${type} = ${JSON.stringify(withAdditive(key, data[key]))};`,
    )
    .join("\n\n");
  const out = [
    "// GENERATED by apps/web/scripts/park-fixtures.mjs from design_handoff_tilo_web_app/design/tilo-app.js.",
    "// Do not edit: change the script or the prototype, then regenerate.",
    `import type { ${names.join(", ")} } from "../types";`,
    "",
    body,
    "",
  ].join("\n");
  fs.writeFileSync(at(`../src/park/api/fixtures/${file}.ts`), out);
}
