// Writes src/park/tokens/themes.css and themes.generated.ts from config/themes/*.json (`just tokens`, FR-WLD-15).
// A theme file lists only the role tokens it changes, for day and for night (colours only, so a file can never put
// other CSS into the stylesheet). Metropolis is the base park.css and overrides nothing. A new file in
// config/themes/ plus `just tokens` is the whole change: no code edit (a drift test pins the committed output).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const at = (p) => fileURLToPath(new URL(p, import.meta.url));
export const THEMES_DIR = at("../../../config/themes");
export const CSS_PATH = at("../src/park/tokens/themes.css");
export const TS_PATH = at("../src/park/tokens/themes.generated.ts");
export const DEFAULT_ID = "metropolis";
const HEADER = "AUTO-GENERATED by apps/web/scripts/generate-themes.mjs; run `just tokens`.";
const ID_RE = /^[a-z][a-z0-9-]{0,31}$/;
const ROLE_RE = /^[A-Za-z][A-Za-z0-9]{0,24}$/;
const COLOUR_RE =
  /^(#[0-9a-fA-F]{3,8}|rgba?\(\s*\d{1,3}\s*,\s*\d{1,3}\s*,\s*\d{1,3}\s*(,\s*(0|1|0?\.\d{1,3})\s*)?\))$/;
const KEYS = new Set(["id", "name", "default", "note", "day", "night"]);

const isMap = (v) => v !== null && typeof v === "object" && !Array.isArray(v);
const tokens = (m) =>
  isMap(m) &&
  Object.entries(m).every(
    ([k, v]) => ROLE_RE.test(k) && typeof v === "string" && COLOUR_RE.test(v),
  );

/** A theme object, or null when the file is not one (unknown key, bad id, a value that is not a plain colour). */
export function parseTheme(raw) {
  if (!isMap(raw) || !Object.keys(raw).every((k) => KEYS.has(k))) return null;
  const { id, name, day, night } = raw;
  if (typeof id !== "string" || !ID_RE.test(id)) return null;
  if (typeof name !== "string" || name.length < 1 || name.length > 40) return null;
  if (typeof raw.default !== "boolean" || !tokens(day) || !tokens(night)) return null;
  if (raw.note !== undefined && (typeof raw.note !== "string" || raw.note.length > 400))
    return null;
  return { id, name, isDefault: raw.default, day, night };
}

/** Every theme in `dir`, Metropolis first then by file name; a bad file, a repeated id or a second default throws. */
export function readThemes(dir = THEMES_DIR) {
  const themes = [];
  for (const file of fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()) {
    let raw;
    try {
      raw = JSON.parse(fs.readFileSync(path.join(dir, file), "utf-8"));
    } catch {
      throw new Error(`${file}: not JSON`);
    }
    const theme = parseTheme(raw);
    if (!theme)
      throw new Error(`${file}: not a theme (id, name, default, day, night; colours only)`);
    if (`${theme.id}.json` !== file) throw new Error(`${file}: the id must equal the file name`);
    themes.push(theme);
  }
  if (themes.filter((t) => t.isDefault).length !== 1)
    throw new Error("exactly one theme must be default");
  const first = themes.find((t) => t.id === DEFAULT_ID);
  if (!first?.isDefault) throw new Error(`${DEFAULT_ID} must exist and be the default`);
  return [first, ...themes.filter((t) => t !== first)];
}

const rule = (sel, map) =>
  Object.keys(map).length === 0
    ? ""
    : `${sel} {\n${Object.entries(map)
        .map(([k, v]) => `  --${k}: ${v.toLowerCase()};`)
        .join("\n")}\n}\n`;

export function generate(dir = THEMES_DIR) {
  const themes = readThemes(dir);
  // By day the theme's rule must not leak into night (equal specificity would let it win by order), hence :not().
  const blocks = themes.flatMap((t) => [
    rule(`[data-park][data-theme="${t.id}"]:not([data-time="night"])`, t.day),
    rule(`[data-park][data-theme="${t.id}"][data-time="night"]`, t.night),
  ]);
  // Written the way Biome formats it (unquoted keys, one key per line), so a format run never changes it.
  const items = themes.map(
    (t) =>
      `  {
    id: ${JSON.stringify(t.id)},
    name: ${JSON.stringify(t.name)},
    isDefault: ${t.isDefault},
  },
`,
  );
  return {
    css: `/* ${HEADER} Role tokens over park.css, per theme, day then night. */
${blocks.join("")}`,
    ts: `// ${HEADER}
export const THEMES = [
${items.join("")}] as const;
export const DEFAULT_THEME = "${DEFAULT_ID}";
`,
  };
}

if (process.argv[1]?.endsWith("generate-themes.mjs")) {
  const { css, ts } = generate();
  fs.writeFileSync(CSS_PATH, css);
  fs.writeFileSync(TS_PATH, ts);
}
